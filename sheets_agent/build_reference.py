"""
Generates src/Reference.js for the Google Sheets DQA Agent from the
Toolbox's Python engines, so both use the same prompts, domain lists and
standard warranties. Run after changing any of them:

    python sheets_agent/build_reference.py
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT.parent / "app"))

from tools.common import oem_reference  # noqa: E402
from tools.dimensions import core as dimensions  # noqa: E402
from tools.firmware_docs import core as firmware  # noqa: E402
from tools.oem_url import core as oem_url  # noqa: E402
from tools.product_name_qa import core as name_qa  # noqa: E402
from tools.status_checker import core as status  # noqa: E402
from tools.warranty import core as warranty  # noqa: E402

ref = {
    "prompts": {
        "name_qa": name_qa.SYSTEM_PROMPT,
        "status": status.SYSTEM_PROMPT,
        "firmware": firmware.SYSTEM_PROMPT,
        "warranty": warranty.SYSTEM_PROMPT,
        "dimensions": dimensions.SYSTEM_PROMPT,
    },
    "knownRetailers": sorted(oem_url.KNOWN_RETAILERS),
    "mfrDomains": {k: sorted(v) for k, v in oem_url.MFR_DOMAINS.items()},
    "twoLevelSuffixes": sorted(oem_url._TWO_LEVEL_SUFFIXES),
    "genericWords": sorted(oem_url._GENERIC_WORDS),
    "oemStandard": [
        {"manufacturer": r["manufacturer"], "standard": r["standard_warranty"],
         "days": r["warranty_days"], "domain": r["website_domain"]}
        for r in oem_reference._entries()
    ],
    "firmwareFlags": {k: list(v) for k, v in firmware.FLAG_FIELDS.items()},
    "productDimNames": list(dimensions.PRODUCT_DIM_NAMES),
    "packageDimNames": list(dimensions.PACKAGE_DIM_NAMES),
}

out = ROOT / "src" / "Reference.js"
out.write_text(
    "// GENERATED by sheets_agent/build_reference.py from the Toolbox engines — do not edit.\n"
    "var REF = " + json.dumps(ref, indent=1, ensure_ascii=False) + ";\n",
    encoding="utf-8",
)
print(f"Wrote {out} ({out.stat().st_size // 1024} KB)")
